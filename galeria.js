// 2. Función para inyectar las fotos en el HTML
function renderizarGaleria() {
    const contenedor = document.getElementById('galeria-grid');
    let html = '';

    fotosGaleria.forEach(foto => {
        // Configuramos si lleva el ícono extra o no
        let svgIcono = '';
        let clasesContenedorTexto = 'items-end justify-center'; // Normal
        
        if (foto.icono) {
            svgIcono = `<svg class="w-6 h-6 text-white mb-1" fill="none" stroke="currentColor" viewBox="0 0 24 24"><path stroke-linecap="round" stroke-linejoin="round" stroke-width="1.5" d="M4 16l4.586-4.586a2 2 0 012.828 0L16 16m-2-2l1.586-1.586a2 2 0 012.828 0L20 14m-6-6h.01M6 20h12a2 2 0 002-2V6a2 2 0 00-2-2H6a2 2 0 00-2 2v12a2 2 0 002 2z"></path></svg>`;
            clasesContenedorTexto = 'flex-col items-center justify-end'; // Para la que tiene ícono
        }

        // Construimos la tarjeta HTML
        html += `
        <div data-categoria="${foto.categoria}" data-personas="${foto.personas}" class="galeria-item relative group overflow-hidden rounded-xl aspect-[4/3] cursor-pointer shadow-sm hover:shadow-md transition-all">
            <img src="${foto.src}" class="w-full h-full object-cover transition-transform duration-700 group-hover:scale-105">
            <div class="absolute inset-0 bg-gradient-to-t from-black/80 via-transparent to-transparent opacity-0 group-hover:opacity-100 transition-opacity duration-300 flex ${clasesContenedorTexto} pb-4">
                ${svgIcono}
                <span class="text-white text-xs text-center font-medium tracking-wider px-2">${foto.personas}</span>
            </div>
        </div>
        `;
    });

    contenedor.innerHTML = html;

    // Le avisamos al HTML que ya terminamos de pintar las fotos
    document.dispatchEvent(new Event('galeriaCargada'));
}

// Arrancar la función apenas cargue la página
document.addEventListener('DOMContentLoaded', renderizarGaleria);